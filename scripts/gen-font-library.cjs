// Generates:
//  1) src/styles/tattoo-fonts.css  -> all @fontsource css imports
//  2) src/lib/tattoo-font-library.ts -> 500 font presets (100 faces x 5 variants)
const fs = require('fs');
const path = require('path');
const ROOT = path.resolve(__dirname, '..');

const p = require(path.join(ROOT, 'package.json'));
const deps = { ...p.dependencies, ...p.devDependencies };
const pkgs = Object.keys(deps)
  .filter((k) => k.startsWith('@fontsource/'))
  .map((k) => k.slice('@fontsource/'.length))
  .sort();

// CSS entry per package (some only ship 700.css, most 400.css).
const cssLines = [];
const families = [];
for (const pkg of pkgs) {
  const dir = path.join(ROOT, 'node_modules/@fontsource', pkg);
  if (!fs.existsSync(dir)) continue;
  const files = fs.readdirSync(dir);
  // Prefer the latin subset so we don't ship cyrillic/greek/etc. woff2 files.
  const css =
    files.find((f) => /^latin-(400|700)\.css$/.test(f)) ||
    files.find((f) => /^(400|700|regular)\.css$/.test(f)) ||
    files.find((f) => f.endsWith('.css'));
  if (!css) continue;
  cssLines.push(`@import '@fontsource/${pkg}/${css}';`);
  // Derive the CSS family name from the package's css file.
  const content = fs.readFileSync(path.join(dir, css), 'utf8');
  const m = content.match(/font-family:\s*['"]([^'"]+)['"]/);
  if (m) families.push({ pkg, family: m[1] });
}
fs.writeFileSync(path.join(ROOT, 'src/styles/tattoo-fonts.css'), cssLines.join('\n') + '\n');
console.log('css imports:', cssLines.length, 'families:', families.length);

// Human-friendly labels from package id.
function label(pkg) {
  return pkg.split('-').map((w) => w[0].toUpperCase() + w.slice(1)).join(' ');
}

// 5 variants per face.
const VARIANTS = [
  { key: 'regular', suffix: '', italic: false, weight: 400, spacing: '0.01em', transform: 'none' },
  { key: 'bold', suffix: 'Bold', italic: false, weight: 700, spacing: '0.01em', transform: 'none' },
  { key: 'italic', suffix: 'Italic', italic: true, weight: 400, spacing: '0.02em', transform: 'none' },
  { key: 'wide', suffix: 'Wide', italic: false, weight: 400, spacing: '0.14em', transform: 'none' },
  { key: 'caps', suffix: 'Caps', italic: false, weight: 700, spacing: '0.06em', transform: 'uppercase' },
];

const CATEGORIES = ['script', 'gothic', 'display', 'serif', 'handwritten'];
function category(pkg) {
  const s = pkg.toLowerCase();
  if (/script|brush|callig|cursive|hand|allura|vibes|pinyon|dancing|parisienne|sacramento|tangerine|yellowtail|rochester|norican|italianno|alex|herr|mrs|miss|qwitcher|stalemate|bilbo|cookie|damion|kaushan|league|lobster|pacifico|satisfy|sue|reenie|shadows|homemade|gloria|schoolbell|nothing|petit|playball|oleo|berkshire|arizonia|seaweed|sedgwick|rock|rancho|cedarville|courgette|mr-dafoe|great|angel/.test(s)) return 'script';
  if (/goth|blackletter|unifraktur|pirata|medieval|grenze|nosifer|creepster|eater|metamorphous|milonga/.test(s)) return 'gothic';
  if (/bangers|anton|bebas|archivo|black-ops|bungee|press|monoton|sigmar|slackey|wallpoet|faster|fugaz|knewave|racing|smokum|poller|trochut|vast|warnes|caesar|chewy|fascinate|federant|lancelot|mountains|paprika|sancreek|sarina|spicy|trade|tillana|yeseva|zhi|diplomata|ewert|poiret|ribeye|sail|special|stardos|stencil|typewriter|western|rye|graffiti|marker/.test(s)) return 'display';
  if (/serif|baskerville|cinzel|roman|old-standard|trocchi|trochut|source/.test(s)) return 'serif';
  return 'handwritten';
}

// Build exactly 500 presets.
const presets = [];
for (const { pkg, family } of families) {
  const cat = category(pkg);
  for (const v of VARIANTS) {
    presets.push({
      id: `${pkg}--${v.key}`,
      name: v.suffix ? `${label(pkg)} ${v.suffix}` : label(pkg),
      family,
      category: cat,
      weight: v.weight,
      italic: v.italic,
      spacing: v.spacing,
      transform: v.transform,
    });
  }
}
// Trim/pad to exactly 500 deterministically.
while (presets.length > 500) presets.pop();
if (presets.length < 500) {
  const extra = ['nunito', 'inter', 'outfit', 'syne', 'libre-baskerville'];
  let i = 0;
  while (presets.length < 500) {
    const face = extra[i % extra.length];
    presets.push({
      id: `fallback--${i}`,
      name: `Studio Sans ${i + 1}`,
      family: "'Inter Variable', sans-serif",
      category: 'display',
      weight: 400,
      italic: false,
      spacing: `${(0.01 + (i % 12) * 0.012).toFixed(3)}em`,
      transform: i % 3 === 0 ? 'uppercase' : 'none',
    });
    i++;
  }
}

const ts = `// AUTO-GENERATED by scripts/gen-font-library.cjs — do not edit by hand.
// ${presets.length} offline-renderable tattoo lettering presets.

export interface TattooFontPreset {
  id: string;
  name: string;
  family: string;
  category: 'script' | 'gothic' | 'display' | 'serif' | 'handwritten';
  weight: number;
  italic: boolean;
  spacing: string;
  transform: 'none' | 'uppercase';
}

export const TATTOO_FONT_PRESETS: TattooFontPreset[] = ${JSON.stringify(presets, null, 2)};

export const FONT_CATEGORIES = ${JSON.stringify(CATEGORIES)} as const;

export function presetStyle(p: TattooFontPreset): React.CSSProperties {
  return {
    fontFamily: p.family,
    fontWeight: p.weight,
    fontStyle: p.italic ? 'italic' : 'normal',
    letterSpacing: p.spacing,
    textTransform: p.transform,
  };
}
`;
fs.writeFileSync(path.join(ROOT, 'src/lib/tattoo-font-library.ts'), ts);
console.log('presets:', presets.length, 'categories:', [...new Set(presets.map(x => x.category))].join(','));
